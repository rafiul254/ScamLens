/**
 * UI strings for the four supported languages.
 * The API returns analysis content already localised; this file only covers the
 * interface chrome. Anything missing falls back to English.
 */
export const LANGUAGES = [
  { code: 'bn', label: 'বাংলা', english: 'Bangla', speech: 'bn-BD' },
  { code: 'en', label: 'English', english: 'English', speech: 'en-IN' },
  { code: 'hi', label: 'हिन्दी', english: 'Hindi', speech: 'hi-IN' },
  { code: 'ur', label: 'اردو', english: 'Urdu', speech: 'ur-PK' },
] as const

export type LangCode = (typeof LANGUAGES)[number]['code']

/** Full English name for a language code, for labels ("Language: English"). */
export function languageName(code: string): string {
  return LANGUAGES.find((l) => l.code === code)?.english ?? 'Unknown'
}

/** A language written in itself, for the switcher ("বাংলা", "हिन्दी"). */
export function languageNative(code: string): string {
  return LANGUAGES.find((l) => l.code === code)?.label ?? code
}

