const DICTS: Record<LangCode, Dict> = { bn, en, hi, ur }

export function translate(lang: LangCode, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? en
  let value = dict[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) value = value.replaceAll(`{${k}}`, String(v))
  }
  return value
}

export function verdictKey(verdict: string): string {
  const map: Record<string, string> = { SAFE: 'safe', SUSPICIOUS: 'suspicious', SCAM: 'scam' }
  return `result.verdict.${map[verdict] ?? 'suspicious'}`
}

export function speechLocale(lang: string): string {
  return LANGUAGES.find((l) => l.code === lang)?.speech ?? 'en-IN'
}
